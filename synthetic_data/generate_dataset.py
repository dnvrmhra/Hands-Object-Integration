"""
generate_dataset.py — ASTRA-HAR Synthetic Dataset Generator
============================================================
Generates 800 training + 200 validation 640×640 PNG images depicting a
simulated ISS Columbus module interior, with YOLO-format bounding-box labels
for four classes:
    0: GLOVEBOX-01
    1: CENTRIFUGE-02
    2: SMP-RED
    3: SMP-YEL

Dependencies: Pillow, NumPy  (no ML libraries required)
Usage:
    python synthetic_data/generate_dataset.py
"""

