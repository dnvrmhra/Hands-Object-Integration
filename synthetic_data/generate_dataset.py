BBox = tuple[int, int, int, int]   # (x1, y1, x2, y2)  pixel coords


def bbox_to_yolo(bbox: BBox, img_size: int = IMG_SIZE) -> tuple[float, float, float, float]:
    """Convert pixel (x1,y1,x2,y2) to normalised YOLO (cx,cy,w,h)."""
    x1, y1, x2, y2 = bbox
    cx = (x1 + x2) / 2 / img_size
    cy = (y1 + y2) / 2 / img_size
    w  = (x2 - x1) / img_size
    h  = (y2 - y1) / img_size
    return cx, cy, w, h


def clamp_bbox(bbox: BBox, margin: int = 0, limit: int = IMG_SIZE) -> BBox:
    """Clamp bbox to image bounds."""
    x1, y1, x2, y2 = bbox
    return (
        max(margin, x1),
        max(margin, y1),
        min(limit - margin - 1, x2),
        min(limit - margin - 1, y2),
    )


def random_position(w: int, h: int, margin: int = 10) -> tuple[int, int]:
    """Return a random (x1, y1) so that the object fits within the image."""
    x1 = RNG.randint(margin, IMG_SIZE - w - margin)
    y1 = RNG.randint(margin, IMG_SIZE - h - margin)
    return x1, y1


# ---- GLOVEBOX-01 -----------------------------------------------------------

def draw_glovebox(draw: ImageDraw.ImageDraw) -> BBox:
    """
    Draw GLOVEBOX-01: a large grey rectangular science glovebox.
    Returns the bounding box (x1, y1, x2, y2).
    """
    gw = RNG.randint(200, 350)
    gh = RNG.randint(150, 280)

    # Prefer centre-left placement; clamp so range is always valid
    x1_hi = max(32, min(IMG_SIZE - gw - 10, IMG_SIZE // 2 - gw // 2 + 60))
    x1 = RNG.randint(30, x1_hi)
    y1_hi = max(int(IMG_SIZE * 0.26), int(IMG_SIZE * 0.55) - gh)
    y1 = RNG.randint(int(IMG_SIZE * 0.25), max(int(IMG_SIZE * 0.25) + 1, y1_hi))
    x2 = min(IMG_SIZE - 5, x1 + gw)
    y2 = min(IMG_SIZE - 5, y1 + gh)

    # --- Outer body with subtle metallic gradient ---
    body_col = _jitter_color((138, 155, 176), 15)
    draw.rectangle([x1, y1, x2, y2], fill=body_col)

    # Metallic highlight (lighter stripe on top)
    hl_col = tuple(min(255, c + 30) for c in body_col)
    draw.rectangle([x1, y1, x2, y1 + gh // 6], fill=hl_col)

    # --- Outer border ---
    border_col = (138, 155, 176)
    for t in range(5):
        draw.rectangle([x1 + t, y1 + t, x2 - t, y2 - t], outline=border_col)

    # --- Inner black window (80% of box, centred) ---
    margin_x = int(gw * 0.10)
    margin_y = int(gh * 0.10)
    wx1 = x1 + margin_x
    wy1 = y1 + margin_y
    wx2 = x2 - margin_x
    wy2 = y2 - margin_y
    win_col = _jitter_color((8, 12, 18), 5)
    draw.rectangle([wx1, wy1, wx2, wy2], fill=win_col)

    # Slight reflection line in window
    refl_col = (20, 30, 45)
    draw.line([(wx1 + 4, wy1 + 4), (wx2 - 4, wy1 + (wy2 - wy1) // 4)], fill=refl_col, width=2)

    # --- Glove port circles (left and right edges) ---
    port_r = RNG.randint(20, 30)
    port_col = (15, 15, 15)
    port_rim_col = _jitter_color((100, 110, 125), 10)
    cy_port = (y1 + y2) // 2

    # Left port
    lx = x1
    draw.ellipse([lx - port_r, cy_port - port_r, lx + port_r, cy_port + port_r],
                 fill=port_rim_col)
    draw.ellipse([lx - port_r + 4, cy_port - port_r + 4,
                  lx + port_r - 4, cy_port + port_r - 4], fill=port_col)

    # Right port
    rx = x2
    draw.ellipse([rx - port_r, cy_port - port_r, rx + port_r, cy_port + port_r],
                 fill=port_rim_col)
    draw.ellipse([rx - port_r + 4, cy_port - port_r + 4,
                  rx + port_r - 4, cy_port + port_r - 4], fill=port_col)

    return clamp_bbox((x1, y1, x2, y2))


# ---- CENTRIFUGE-02 ---------------------------------------------------------

def draw_centrifuge(draw: ImageDraw.ImageDraw, glovebox_bbox: BBox | None) -> BBox:
    """
    Draw CENTRIFUGE-02: a circular centrifuge rotor with radial spokes.
    Placed inside or adjacent to the glovebox when possible.
    Returns the bounding box.
    """
    r = RNG.randint(40, 70)

    # Try to place near/inside glovebox, with safe fallback
    if glovebox_bbox is not None:
        gx1, gy1, gx2, gy2 = glovebox_bbox
        cx_lo = max(r + 5, gx1 + r + 10)
        cx_hi = min(IMG_SIZE - r - 5, gx2 - r - 10)
        cy_lo = max(r + 5, gy1 + r + 10)
        cy_hi = min(IMG_SIZE - r - 5, gy2 - r - 10)
        # Fallback to full image if glovebox too small
        if cx_lo >= cx_hi or cy_lo >= cy_hi:
            cx = RNG.randint(r + 10, IMG_SIZE - r - 10)
            cy_c = RNG.randint(r + 10, IMG_SIZE - r - 10)
        else:
            cx = RNG.randint(cx_lo, cx_hi)
            cy_c = RNG.randint(cy_lo, cy_hi)
    else:
        cx = RNG.randint(r + 10, IMG_SIZE - r - 10)
        cy_c = RNG.randint(r + 10, IMG_SIZE - r - 10)

    # --- Base silver circle ---
    base_col = _jitter_color((160, 165, 175), 15)
    draw.ellipse([cx - r, cy_c - r, cx + r, cy_c + r], fill=base_col)

    # --- Radial spokes ---
    n_spokes = RNG.randint(6, 8)
    angle_offset = RNG.uniform(0, 2 * math.pi)
    spoke_col = _jitter_color((90, 95, 105), 10)
    hub_r = max(6, int(r * 0.22))
    for i in range(n_spokes):
        angle = angle_offset + i * (2 * math.pi / n_spokes)
        sx = cx + int((r - 3) * math.cos(angle))
        sy = cy_c + int((r - 3) * math.sin(angle))
        draw.line([(cx, cy_c), (sx, sy)], fill=spoke_col, width=2)

    # --- Central hub ---
    hub_col = _jitter_color((60, 65, 75), 10)
    draw.ellipse([cx - hub_r, cy_c - hub_r, cx + hub_r, cy_c + hub_r], fill=hub_col)
    # Hub highlight
    draw.arc([cx - hub_r, cy_c - hub_r, cx + hub_r, cy_c + hub_r],
             start=200, end=340, fill=(120, 125, 135), width=2)

    return clamp_bbox((cx - r, cy_c - r, cx + r, cy_c + r))


# ---- SMP tubes (RED and YELLOW) --------------------------------------------

def draw_smp(draw: ImageDraw.ImageDraw, cap_color: tuple[int, int, int],
             existing: list[BBox]) -> BBox | None:
    """
    Draw a Sample Management Pouch (SMP) tube: small white/grey rectangle
    with a coloured cap on top. Avoids overlapping existing bboxes.
    Returns the bounding box, or None if no valid position found.
    """
    tw = RNG.randint(12, 22)   # tube width
    th = RNG.randint(35, 65)   # tube total height
    cap_h = max(8, int(th * 0.25))

    # --- Try up to 30 random positions ---
    for _ in range(30):
        x1, y1 = random_position(tw, th, margin=20)
        x2 = x1 + tw
        y2 = y1 + th

        # Check against existing bboxes (allow small overlap)
        overlap = False
        for ex1, ey1, ex2, ey2 in existing:
            if not (x2 < ex1 - 4 or x1 > ex2 + 4 or y2 < ey1 - 4 or y1 > ey2 + 4):
                overlap = True
                break
        if overlap:
            continue

        # --- Tube body (white/light-grey) ---
        body_col = _jitter_color((232, 236, 240), 12)
        draw.rectangle([x1, y1, x2, y2], fill=body_col)

        # Subtle body shading (right edge darker)
        shade_col = tuple(max(0, c - 25) for c in body_col)
        draw.rectangle([x2 - 3, y1, x2, y2], fill=shade_col)

        # --- Coloured cap ---
        cap_col = tuple(max(0, min(255, c + RNG.randint(-15, 15))) for c in cap_color)
        draw.rectangle([x1, y1, x2, y1 + cap_h], fill=cap_col)

        # --- Thin grey rim ring between cap and body ---
        rim_col = _jitter_color((150, 155, 160), 8)
        draw.rectangle([x1, y1 + cap_h, x2, y1 + cap_h + 2], fill=rim_col)

        return clamp_bbox((x1, y1, x2, y2))

    return None   # Could not place


# ---------------------------------------------------------------------------
# Full scene composition
# ---------------------------------------------------------------------------

def compose_scene() -> tuple[Image.Image, list[tuple[int, float, float, float, float]]]:
    """
    Build one 640×640 scene:
      1. Draw background
      2. Place GLOVEBOX-01 (always)
      3. Maybe place CENTRIFUGE-02 (70% chance)
      4. Place 1-4 SMP-RED tubes
      5. Place 1-4 SMP-YEL tubes
      6. Apply augmentations
    Returns (PIL Image, list_of_yolo_labels).
    Each label: (class_id, cx, cy, w, h)  — all normalised 0-1.
    """
    img = Image.new("RGB", (IMG_SIZE, IMG_SIZE), (0, 0, 0))
    draw = ImageDraw.Draw(img)
    arr = np.array(img, dtype=np.uint8)

    # Step 1: Background (draw onto `draw` first, then extract array)
    draw_background(draw, arr)

    # Convert drawn image back to array for pixel-level effects
    arr = np.array(img, dtype=np.uint8)

    # Brightness jitter on background
    arr = apply_brightness_jitter(arr, (0.85, 1.15))

    # Gaussian noise (optional, 60% probability)
    if RNG.random() < 0.60:
        sigma = RNG.uniform(8, 15)
        arr = apply_noise(arr, sigma)

    # Vignette (optional, 50% probability)
    if RNG.random() < 0.50:
        arr = apply_vignette(arr, strength=RNG.uniform(0.3, 0.6))

    # Convert back to PIL for object drawing
    img = Image.fromarray(arr)
    draw = ImageDraw.Draw(img)

    labels: list[tuple[int, float, float, float, float]] = []

    # Step 2: GLOVEBOX-01 (always)
    gb_bbox = draw_glovebox(draw)
    labels.append((CLS_GLOVEBOX, *bbox_to_yolo(gb_bbox)))

    placed_bboxes: list[BBox] = [gb_bbox]

    # Step 3: CENTRIFUGE-02 (70% chance)
    if RNG.random() < 0.70:
        cf_bbox = draw_centrifuge(draw, gb_bbox)
        labels.append((CLS_CENTRIFUGE, *bbox_to_yolo(cf_bbox)))
        placed_bboxes.append(cf_bbox)

    # Step 4: SMP-RED tubes (1-4)
    n_red = RNG.randint(1, 4)
    for _ in range(n_red):
        bbox = draw_smp(draw, (229, 62, 62), placed_bboxes)
        if bbox is not None:
            labels.append((CLS_SMP_RED, *bbox_to_yolo(bbox)))
            placed_bboxes.append(bbox)

    # Step 5: SMP-YEL tubes (1-4)
    n_yel = RNG.randint(1, 4)
    for _ in range(n_yel):
        bbox = draw_smp(draw, (246, 173, 85), placed_bboxes)
        if bbox is not None:
            labels.append((CLS_SMP_YEL, *bbox_to_yolo(bbox)))
            placed_bboxes.append(bbox)

    # ---- Augmentations ----

    # Horizontal flip (50%)
    if RNG.random() < 0.50:
        img = img.transpose(Image.FLIP_LEFT_RIGHT)
        # Mirror cx for labels
        labels = [
            (cls, 1.0 - cx, cy, w, h)
            for cls, cx, cy, w, h in labels
        ]

    # Gaussian blur (30%)
    if RNG.random() < 0.30:
        sigma = RNG.uniform(0.5, 1.5)
        img = img.filter(ImageFilter.GaussianBlur(radius=sigma))

    # Motion blur (15%) -- numpy-based horizontal motion blur
    # (Pillow Kernel filter only supports size=3 in newer Pillow versions)
    if RNG.random() < 0.15:
        k = RNG.choice([3, 5, 7])
        arr_mb = np.array(img, dtype=np.float32)
        blurred = arr_mb.copy()
        for shift in range(1, k):
            blurred += np.roll(arr_mb, shift, axis=1)
        blurred /= k
        img = Image.fromarray(np.clip(blurred, 0, 255).astype(np.uint8))

    return img, labels


