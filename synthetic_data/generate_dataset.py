# Dataset generation loop
# ---------------------------------------------------------------------------

def generate_split(
    n: int,
    img_dir: Path,
    lbl_dir: Path,
    split_name: str,
    start_idx: int = 0,
) -> dict[int, int]:
    """
    Generate `n` images + labels for one split.
    Returns a dict counting labels per class.
    """
    counts: dict[int, int] = {k: 0 for k in range(4)}

    for i in range(n):
        idx = start_idx + i
        img, labels = compose_scene()

        # Save image
        img_path = img_dir / f"frame_{idx:05d}.png"
        img.save(img_path)

        # Save labels
        lbl_path = lbl_dir / f"frame_{idx:05d}.txt"
        lines = [f"{cls} {cx:.6f} {cy:.6f} {w:.6f} {h:.6f}\n"
                 for cls, cx, cy, w, h in labels]
        lbl_path.write_text("".join(lines))

        # Update counts
        for cls, *_ in labels:
            counts[cls] += 1

        # Progress report
        if (i + 1) % 50 == 0 or (i + 1) == n:
            print(f"  Generated {i + 1:>4}/{n} {split_name} images...")

    return counts


def main() -> None:
    """Entry point: generate the full synthetic dataset."""
    print("=" * 60)
    print("  ASTRA-HAR Synthetic Dataset Generator")
    print("=" * 60)

    ensure_dirs()
    write_yaml()

    print()
    print(f"[Training split]  {N_TRAIN} images -> {IMG_TRAIN}")
    train_counts = generate_split(N_TRAIN, IMG_TRAIN, LBL_TRAIN, "training",  start_idx=0)

    print()
    print(f"[Validation split] {N_VAL} images -> {IMG_VAL}")
    val_counts   = generate_split(N_VAL,   IMG_VAL,   LBL_VAL,   "validation", start_idx=N_TRAIN)

    # ---- Summary ----
    print()
    print("=" * 60)
    print("  SUMMARY")
    print("=" * 60)
    print(f"  Total images generated : {N_TRAIN + N_VAL}")
    print(f"  Training images        : {N_TRAIN}")
    print(f"  Validation images      : {N_VAL}")
    print()
    print("  Label counts per class (training):")
    for cls_id, name in CLASS_NAMES.items():
        print(f"    [{cls_id}] {name:<18} : {train_counts[cls_id]:>5} labels")
    print()
    print("  Label counts per class (validation):")
    for cls_id, name in CLASS_NAMES.items():
        print(f"    [{cls_id}] {name:<18} : {val_counts[cls_id]:>5} labels")
    print()
    print(f"  data.yaml -> {YAML_PATH}")
    print("  Dataset generation complete!")
    print("=" * 60)


if __name__ == "__main__":
    main()
