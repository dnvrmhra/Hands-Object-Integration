def _jitter_color(base: tuple[int, int, int], delta: int = 20) -> tuple[int, int, int]:
    """Return a random colour near `base` by ±delta per channel."""
    return tuple(
        max(0, min(255, c + RNG.randint(-delta, delta)))
        for c in base
    )


def draw_background(draw: ImageDraw.ImageDraw, arr: np.ndarray) -> None:
    """
    Paint the ISS Columbus module interior:
      - Dark blue-grey base
      - Rack panel grid lines
      - Bolt/screw circles at intersections
      - Viewing window area (top-centre)
      - Instrument panel rectangles
    """
    S = IMG_SIZE

    # --- Base fill (dark blue-grey, slight gradient top→bottom) ---
    base_top    = (RNG.randint(13, 20), RNG.randint(17, 26), RNG.randint(23, 35))
    base_bottom = (RNG.randint(18, 30), RNG.randint(25, 40), RNG.randint(35, 55))
    for y in range(S):
        t = y / S
        r = int(base_top[0] * (1 - t) + base_bottom[0] * t)
        g = int(base_top[1] * (1 - t) + base_bottom[1] * t)
        b = int(base_top[2] * (1 - t) + base_bottom[2] * t)
        draw.line([(0, y), (S - 1, y)], fill=(r, g, b))

    # --- Rack panel grid lines ---
    panel_color = _jitter_color((55, 65, 80), 10)
    # Vertical rack dividers
    v_positions = [int(S * f) for f in (0.22, 0.44, 0.66, 0.88)]
    for x in v_positions:
        w = RNG.randint(1, 2)
        draw.rectangle([x, 0, x + w, S], fill=panel_color)

    # Horizontal shelf lines
    h_positions = [int(S * f) for f in (0.20, 0.40, 0.60, 0.80)]
    for y in h_positions:
        w = RNG.randint(1, 2)
        draw.rectangle([0, y, S, y + w], fill=panel_color)

    # --- Bolt circles at intersections ---
    bolt_color = _jitter_color((70, 80, 95), 8)
    for x in v_positions:
        for y in h_positions:
            r = RNG.randint(3, 5)
            draw.ellipse([x - r, y - r, x + r, y + r], fill=bolt_color)

    # --- Viewing window (top-centre) ---
    wx1, wy1 = int(S * 0.30), int(S * 0.03)
    wx2, wy2 = int(S * 0.70), int(S * 0.18)
    win_frame = _jitter_color((80, 95, 110), 10)
    win_inner = _jitter_color((5, 10, 20), 5)
    draw.rectangle([wx1, wy1, wx2, wy2], fill=win_frame)
    inset = 8
    draw.rectangle([wx1 + inset, wy1 + inset, wx2 - inset, wy2 - inset], fill=win_inner)
    # Simulate stars / space through window
    for _ in range(RNG.randint(4, 12)):
        sx = RNG.randint(wx1 + inset + 2, wx2 - inset - 2)
        sy = RNG.randint(wy1 + inset + 2, wy2 - inset - 2)
        br = RNG.randint(180, 255)
        draw.point((sx, sy), fill=(br, br, br))

    # --- Instrument panel strips (bottom band) ---
    ip_y1 = int(S * 0.88)
    ip_color = _jitter_color((30, 38, 50), 8)
    draw.rectangle([0, ip_y1, S, S], fill=ip_color)
    # Small indicator rectangles on instrument panel
    for i in range(8):
        ix = 20 + i * int(S / 8.5)
        iy = ip_y1 + 15
        iw, ih = RNG.randint(30, 55), RNG.randint(12, 22)
        indicator_col = _jitter_color((45, 55, 70), 12)
        draw.rectangle([ix, iy, ix + iw, iy + ih], fill=indicator_col)


def apply_noise(arr: np.ndarray, sigma: float = 10.0) -> np.ndarray:
    """Add Gaussian noise to a uint8 NumPy image array."""
    noise = np.random.normal(0, sigma, arr.shape)
    noisy = np.clip(arr.astype(np.float32) + noise, 0, 255).astype(np.uint8)
    return noisy


def apply_vignette(arr: np.ndarray, strength: float = 0.5) -> np.ndarray:
    """Apply a radial vignette (darken corners) to the image."""
    S = arr.shape[0]
    cx, cy = S / 2, S / 2
    Y, X = np.ogrid[:S, :S]
    dist = np.sqrt((X - cx) ** 2 + (Y - cy) ** 2)
    max_dist = math.sqrt(cx ** 2 + cy ** 2)
    mask = 1.0 - strength * (dist / max_dist)
    mask = np.clip(mask, 0, 1)
    vignette = (arr * mask[:, :, np.newaxis]).astype(np.uint8)
    return vignette


def apply_brightness_jitter(arr: np.ndarray, factor_range: tuple[float, float] = (0.85, 1.15)) -> np.ndarray:
    """Randomly brighten or darken the image."""
    factor = RNG.uniform(*factor_range)
    adjusted = np.clip(arr.astype(np.float32) * factor, 0, 255).astype(np.uint8)
    return adjusted


